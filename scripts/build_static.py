#!/usr/bin/env python3
"""Write apps/web/config.js for static hosting (Vercel).

The dashboard page loads an optional config.js before its main script. This
script writes that file from the environment so the page runs in static mode:
data comes straight from Supabase (briefs, archive_index) with the reader's
session, and there is no container API.

Reads (first match wins):
    SUPABASE_URL        or NEXT_PUBLIC_SUPABASE_URL
    SUPABASE_ANON_KEY   or SUPABASE_PUBLISHABLE_KEY or NEXT_PUBLIC_SUPABASE_ANON_KEY
    REQUIRE_AUTH        default 1

Writes:
    window.AEGIS_CONFIG = {apiBase:'', supabaseUrl, supabaseAnonKey, requireAuth, mode:'static'}

Safety:
    Refuses to write a service role key (legacy JWT with role=service_role, or
    an sb_secret_ key). That key bypasses RLS and must never reach a browser.
    Never prints key values.

Usage:
    SUPABASE_URL=https://x.supabase.co SUPABASE_ANON_KEY=... python3 scripts/build_static.py
    python3 scripts/build_static.py --allow-empty    # no Supabase: leave AEGIS_CONFIG unset (demo data)
    python3 scripts/build_static.py --out path/to/config.js
"""

from __future__ import annotations

import argparse
import base64
import json
import os
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DEFAULT_OUT = REPO / "apps" / "web" / "config.js"


def env_first(*names: str) -> str:
    for n in names:
        v = os.environ.get(n, "").strip()
        if v:
            return v
    return ""


def truthy(v: str) -> bool:
    return v.strip().lower() in ("1", "true", "yes", "on")


def jwt_role(token: str) -> str | None:
    parts = token.split(".")
    if len(parts) != 3:
        return None
    try:
        pad = "=" * (-len(parts[1]) % 4)
        payload = json.loads(base64.urlsafe_b64decode(parts[1] + pad))
    except (ValueError, json.JSONDecodeError):
        return None
    return payload.get("role") if isinstance(payload, dict) else None


def fail(msg: str) -> None:
    print(f"build_static: {msg}", file=sys.stderr)
    sys.exit(1)


def main() -> None:
    ap = argparse.ArgumentParser(description="Write apps/web/config.js for static (Supabase-only) hosting.")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument(
        "--allow-empty",
        action="store_true",
        help="without Supabase env, write a config.js that leaves AEGIS_CONFIG unset (page shows demo data)",
    )
    args = ap.parse_args()

    url = env_first("SUPABASE_URL", "NEXT_PUBLIC_SUPABASE_URL").rstrip("/")
    key = env_first("SUPABASE_ANON_KEY", "SUPABASE_PUBLISHABLE_KEY", "NEXT_PUBLIC_SUPABASE_ANON_KEY")
    require_auth = truthy(os.environ.get("REQUIRE_AUTH", "1"))

    if not url or not key:
        if not args.allow_empty:
            fail(
                "SUPABASE_URL and SUPABASE_ANON_KEY are required for static mode. "
                "Set them in the Vercel project (or pass --allow-empty for a demo build)."
            )
        # No config at all: per CONTRACT section 7 the page falls back to its
        # embedded synthetic data. Write a file that leaves AEGIS_CONFIG unset.
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(
            "/* Generated by scripts/build_static.py with --allow-empty. No Supabase configured; "
            "the page uses its embedded demo data. */\n",
            encoding="utf-8",
        )
        print("build_static: wrote demo config (AEGIS_CONFIG left unset)")
        return
    if not url.startswith("https://") and not url.startswith(("http://localhost", "http://127.0.0.1")):
        fail("SUPABASE_URL must start with https://")
    if key.startswith("sb_secret_") or jwt_role(key) == "service_role":
        fail("the key provided is a SERVICE key. Use the anon / publishable key. Nothing was written.")

    mode = "static"
    config = {
        "apiBase": "",
        "supabaseUrl": url,
        "supabaseAnonKey": key,
        "requireAuth": require_auth,
        "mode": mode,
    }
    body = (
        "/* Generated by scripts/build_static.py. Do not edit or commit. */\n"
        "window.AEGIS_CONFIG = " + json.dumps(config, indent=2, sort_keys=True) + ";\n"
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(body, encoding="utf-8")

    try:
        shown = args.out.resolve().relative_to(REPO)
    except ValueError:
        shown = args.out
    print(
        f"build_static: wrote {shown} "
        f"(mode={mode}, requireAuth={str(require_auth).lower()})"
    )


if __name__ == "__main__":
    main()
